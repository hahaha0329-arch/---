# --- 웹앱 UI 구성 ---
st.title("🎸 오늘의 하현상 플레이리스트")

# 1. 앱 접속 시 5가지 기분 목록과 함께 "오늘의 기분은 어떤가요?" 표시
mood_options = ["슬픔", "화나는", "신나는", "행복함", "우울함"]
selected_mood = st.selectbox(
    "오늘의 기분은 어떤가요?",
    options=mood_options,
    index=None,
    placeholder="5가지 기분 중 하나를 선택해 주세요"
)

# 2. 사용자가 5가지 기분 중 하나를 선택하면 랜덤으로 추천 실행
if selected_mood:
    # random.sample을 활용해 해당 기분에 맞는 곡들 중 무작위 2곡 추출
    recommended_list = random.sample(songs_by_mood[selected_mood], k=2)
    
    df = pd.DataFrame(recommended_list)
    
    st.subheader(f"✨ '{selected_mood}' 기분일 때 추천하는 하현상 음악")
    
    # 텍스트가 아닌 테이블(표) 형태로 표시 (곡 제목과 앨범명이 명확히 드러남)
    st.table(df.set_index("곡 제목"))
    
    # 같은 기분 내에서 다른 랜덤 추천을 보고 싶을 때를 위한 버튼
    if st.button("🔄 다른 곡 랜덤 추천받기"):
        st.rerun()
        
    st.divider()
    # 추천 음악 목록과 함께 "좋은 하루 보내세요" 출력
    st.success("좋은 하루 보내세요")
